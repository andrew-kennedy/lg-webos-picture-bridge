    assert.equal(broad.edits.length,4);assert.equal(broad.revision,8);
    assert.deepEqual(broad.edits.map(e=>e.bank_id),['pc_sdr','pc_sdr_game','pc_sdrALLM_game','pc_sdr_motion']);
    assert.equal(await page.evaluate(()=>window.fixture.revision),9,'Broad edits use one revision, not one per native bank');
    assert.equal(await page.evaluate(()=>window.fixture.document.banks.find(b=>b.id==='pc_hdr').settings.color),50);
    await button('Restore selected').click();await button('Restore selected settings').click();
    await page.getByText('Saved on the TV.',{exact:false}).waitFor();
    assert.deepEqual((await calls('restore')).at(-1).selection,{pc_sdr:['realCinema'],pc_sdr_motion:['truMotionMode']},'Restoring Motion must never restore the entire Picture bank');
    await page.evaluate(()=>{window.fixture.overrides.pc_sdr={realCinema:'on',color:57};});
    await button('Keep adjustments').click();await button('Keep these adjustments').click();
    await page.getByText('Saved on the TV.',{exact:false}).waitFor();
    assert.deepEqual((await calls('save')).at(-1).selection,{pc_sdr:['realCinema']});
    assert.deepEqual((await calls('save')).at(-1).expected,{pc_sdr:{realCinema:'on'}});
    assert.equal(await page.evaluate(()=>window.fixture.overrides.pc_sdr.color),57);
    await button('Picture').click();await color.fill('52');
    await setScope('format',['hdr']);
    assert(await page.getByText('3 outside this selection',{exact:false}).isVisible());
    await page.evaluate(()=>{window.failNextBatch='before';});
    await page.getByRole('button',{name:'Review 3 changes',exact:true}).click();await button('Save standards').click();
    await page.getByText('Unsaved drafts remain for review.',{exact:false}).waitFor();
    assert.equal(await page.evaluate(()=>Object.keys(document.querySelector('lg-profile-editor').draft).length),3);
    await save();
    assert.deepEqual((await calls('edit_many')).at(-1).edits.map(e=>e.bank_id),['pc_sdr','pc_sdr_game','pc_sdrALLM_game'],'Retry retains the original SDR target set despite current HDR filters');
    await setScope('format',['sdr']);await color.fill('53');
    await page.evaluate(()=>{window.failNextBatch='after';});
    await page.getByRole('button',{name:'Review 3 changes',exact:true}).click();await button('Save standards').click();
    await page.getByText('Reply lost',{exact:false}).waitFor();
    assert.equal(await page.evaluate(()=>Object.keys(document.querySelector('lg-profile-editor').draft).length),0,'A committed batch with a lost response must not be sent twice');
    assert.equal(await color.inputValue(),'53');
    await control('spinbutton','OLED pixel brightness · All SDR game profiles').fill('75');
    await page.getByRole('button',{name:'Review 1 changes',exact:true}).click();
    const targets=await page.locator('.review .targets li').allTextContents();
    assert.equal(targets.length,3);assert(targets.some(t=>t.includes('HDMI 4')));assert(targets.some(t=>t.includes('HDMI 3')),'Global brightness preview expands beyond narrowed HDMI 1 scope');
    await button('Save standards').click();await page.getByText('Saved on the TV.',{exact:false}).waitFor();
    assert.deepEqual((await calls('edit_many')).at(-1).edits,[]);
    assert.deepEqual((await calls('edit_many')).at(-1).preferences,{game_sdr:75});
    await button('Motion').click();await setScope('port',['hdmi1','hdmi3','hdmi4']);await ready();
    const cinema=control('combobox','Real Cinema · SDR');assert.equal(await cinema.inputValue(),'');
    assert.equal(await cinema.locator('option:checked').textContent(),'Mixed');
    await setScope('family',['movie']);assert.equal(await cinema.inputValue(),'on');
    await cinema.selectOption('off');await save();
    assert.deepEqual((await calls('edit_many')).at(-1).edits,[{bank_id:'movie_filmMaker',variant:'standard',settings:{realCinema:'off'}}]);
    await button('HDMI connection').click();await ready();
    await control('combobox','165 Hz boost · All formats').waitFor();
