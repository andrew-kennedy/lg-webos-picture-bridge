    const initial=structuredClone(fixture);initial.document.banks.find(b=>b.id==='pc_sdr_game').settings.gameColorDepth=55;
    await mount(page,initial);
    const control=(role,name)=>page.getByRole(role,{name,exact:true});
    const button=name=>control('button',name),color=control('spinbutton','Color depth · SDR');
    const calls=action=>page.evaluate(action=>window.calls.filter(c=>c.action===action),action);
    const setScope=async(key,selected)=>{
      for(const chip of await page.locator('lg-profile-editor button[data-focus^="scope:'+key+':"]').all()) {
        const value=(await chip.getAttribute('data-focus')).split(':').at(-1),on=await chip.getAttribute('aria-pressed')==='true';
        if(on!==selected.includes(value))await chip.click();
      }
    };
    const ready=()=>page.waitForFunction(()=>{const e=document.querySelector('lg-profile-editor');return e.state&&e.selectedRecords().every(r=>e.live[r.bank.id]);});
    const save=async()=>{
      await page.getByRole('button',{name:/^Review (\d+ changes|against latest)$/}).click();
      await button('Save standards').click();await page.getByText('Saved on the TV.',{exact:false}).waitFor();
    };
    await ready();
    assert.equal(await page.getByRole('heading',{name:'OLED pixel brightness',exact:true}).count(),1,'SDR, HDR and DV brightness must appear together');
