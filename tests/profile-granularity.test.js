'use strict';
const assert=require('node:assert/strict');
const {fixture,doc}=require('./profile-engine.test');
const model=require('../app/bridge/lib/profile-model');
const view=require('../app/profile-view');
module.exports=async function(){
  const collection=model.clone(doc);
  for(const [id,input] of [['pc','hdmi1_pc'],['switch','hdmi3']])collection.banks.push({id,name:id,target:{category:'picture',dimension:{input,pictureMode:'game'}},settings:{backlight:12},brightness_role:'game_sdr'});
  collection.banks.push({id:'hdr',name:'HDR',target:{category:'picture',dimension:{input:'hdmi3',pictureMode:'hdrFilmMaker'}},settings:{backlight:100}});
  collection.banks.push({id:'motion',name:'Motion',target:{category:'picture',dimension:{input:'hdmi3',pictureMode:'filmMaker'},app_id:'com.webos.app.hdmi3'},settings:{truMotionMode:'off'}});
  const f=fixture(collection),e=f.create();e.setPower('on');await e.idle();
  await e.command({action:'initialize',document:collection,enabled:true,migration_id:'test',room:'dark'});
  const command=(action,fields={})=>e.command({action,revision:e.status().revision,...fields});
  const link=(id,linked)=>command('set_brightness_links',{links:[{bank_id:id,linked}]});
  const profile=id=>e.snapshot().document.banks.find(b=>b.id===id);
  const writes=()=>f.writes.filter(n=>n==='profiles').length;
  f.observe(e,'pc','backlight',75);
  const applications=f.operations.filter(o=>o.action==='apply').length;
  await link('pc',false);await e.idle();
  assert.equal(profile('pc').settings.backlight,80,'Unlink freezes the effective standard, not stale saved values or temporary changes');
  assert.equal(profile('pc').brightness_role,undefined);
  assert.equal(e.snapshot().overrides.pc.backlight,75);
  assert.equal(f.operations.filter(o=>o.action==='apply').length,applications,'Unlinking does not change the picture');
  let count=writes();await link('pc',false);await e.idle();assert.equal(writes(),count,'Repeating link state writes no standards');
  await command('edit_many',{edits:[{bank_id:'pc',settings:{backlight:70}}]});await e.idle();
  assert.equal(f.values.pc.backlight,70);assert.equal(f.values.switch.backlight,80);
  await command('set_brightness',{values:{game_sdr:90}});await e.idle();
  assert.equal(f.values.pc.backlight,70);assert.equal(f.values.switch.backlight,90,'Shared sliders affect linked profiles only');
  f.observe(e,'pc','backlight',65);e.setPower('off');await e.idle();e.setPower('on');await e.idle();
  assert.equal(f.values.pc.backlight,70,'Independent standards restore after standby');
  const snapshot=model.clone(e.snapshot().document);count=writes();
  await assert.rejects(command('set_brightness_links',{links:[{bank_id:'pc',linked:true},{bank_id:'hdr',linked:true}]}),/SDR/);
  assert.deepEqual(e.snapshot().document,snapshot);assert.equal(writes(),count,'Invalid later targets cannot partially commit links');
  await assert.rejects(command('set_brightness_links',{revision:0,links:[{bank_id:'pc',linked:true}]}),/refresh/);
  await link('pc',true);await e.idle();assert.equal(f.values.pc.backlight,90);
  assert.equal(profile('pc').brightness_role,'game_sdr');
  await link('movie',false);await e.idle();
  assert.equal(profile('movie').settings.backlight,3);
  assert.deepEqual(profile('movie').variants,{bright:{backlight:100},dark:{backlight:3}});
  await command('edit_many',{edits:[{bank_id:'movie',variant:'bright',settings:{backlight:60}}]});await e.idle();
  assert.equal(f.values.movie.backlight,3,'Inactive room edits stay inactive');
  await e.command({action:'set_environment',room:'bright'});assert.equal(f.values.movie.backlight,60);
  await command('set_brightness',{values:{movie_bright:95}});assert.equal(f.values.movie.backlight,60);
  await link('movie',true);await e.idle();assert.equal(f.values.movie.backlight,95);
  await e.command({action:'set_environment',room:'dark'});assert.equal(f.values.movie.backlight,3);
  const scope={port:['hdmi1'],format:['sdr'],family:['game']};
  assert.deepEqual(view.scopeSelection(e.snapshot(),scope,['picture']),{pc:['backlight'],switch:['backlight']},'Narrow scope expands a linked brightness preference to its complete affected set');
  f.observe(e,'pc','backlight',30);f.observe(e,'switch','backlight',40);f.observe(e,'movie','color',62);
  let restored=await command('restore_scope',{filters:scope,categories:['picture']});
  assert.deepEqual(restored.selection,{pc:['backlight'],switch:['backlight']});
  assert.equal(f.values.pc.backlight,90);assert.equal(f.values.switch.backlight,90);assert.equal(f.values.movie.color,62);
  await link('pc',false);await e.idle();
  assert.deepEqual(view.scopeSelection(e.snapshot(),scope,['picture']),{pc:['backlight']});
  for(const filters of [{pot:['hdmi1']},{port:[]},{port:['hdmi9']},{format:['HDR']}])await assert.rejects(command('restore_scope',{filters}),/scope|filter/);
  // Enrollment captures existing native values once without applying anything.
  for(const id of ['movie','hdr'])Object.assign(f.values[id],{truMotionJudder:0,truMotionBlur:10});
  const apps=f.operations.filter(o=>o.action==='apply').length;count=writes();
  await command('include_motion_controls');assert.equal(writes(),count+1);
  assert.equal(profile('movie').settings.truMotionBlur,10);assert.equal(profile('movie').settings.truMotionJudder,0);
  assert.equal(f.operations.filter(o=>o.action==='apply').length,apps);
  assert.equal(e.snapshot().overrides.movie.color,62,'Adding controls preserves temporary edits');
  count=writes();await command('include_motion_controls');assert.equal(writes(),count,'Enrollment is idempotent');
  await assert.rejects(command('edit_many',{edits:[{bank_id:'movie',settings:{truMotionJudder:2}}]}),/User Selection/);
  f.descriptionHook((bank,ds)=>{for(const d of ds)if(d.key==='truMotionMode')d.values.arrayExt.push({value:'user',active:true,visible:true});});
  await command('edit_many',{edits:[{bank_id:'movie',settings:{truMotionJudder:2,truMotionBlur:8}},{bank_id:'motion',settings:{truMotionMode:'user'}}]});await e.idle();
  assert.equal(f.values.movie.truMotionJudder,2);assert.equal(f.values.movie.truMotionBlur,8);
  await assert.rejects(command('edit_many',{edits:[{bank_id:'movie',settings:{truMotionBlur:11}}]}),/range|between/);
  await command('edit_many',{edits:[{bank_id:'motion',settings:{truMotionMode:'off'}}]});await e.idle();
  restored=await command('restore_scope',{filters:{family:['movie'],format:['sdr']},categories:['motion']});
  assert.deepEqual(restored.selection,{motion:['truMotionMode']});
  assert(restored.excluded.some(v=>v.key==='truMotionBlur'));
  assert.equal(f.values.movie.color,62,'Applying Motion does not restore unrelated picture controls');
  f.inspectHook(()=>e.contextChanged({input:'hdmi4',mode:'hdrGame',range:'hdrALLM',ready:true}));
  await assert.rejects(command('restore_scope',{filters:scope,categories:['picture']}),/signal/);
  f.inspectHook(null);e.stop();
};
