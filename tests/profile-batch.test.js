'use strict';
const assert=require('node:assert/strict');
const {fixture,doc}=require('./profile-engine.test');
const model=require('../app/bridge/lib/profile-model');
module.exports=async()=>{
  const collection=model.clone(doc);
  collection.banks[1].settings.realCinema='on';
  collection.banks.push({...model.clone(collection.banks[1]),id:'movie2',target:{category:'picture',dimension:{input:'hdmi4',pictureMode:'filmMaker'}}});
  const f=fixture(collection),e=f.create();e.setPower('on');await e.idle();
  await e.command({action:'initialize',document:collection,enabled:true,migration_id:'test',room:'dark'});
  const writes=()=>f.writes.filter(n=>n==='profiles').length;
  const batch=(edits,extra={})=>e.command({action:'edit_many',edits,revision:e.status().revision,...extra});
  const edit=(bank_id,settings,variant='standard')=>({bank_id,settings,variant});
  const selection=(action,keys,expected)=>({action,selection:keys,expected,room:'dark',revision:e.status().revision});
  assert.equal(e.status().editor_api,3);
  let count=writes(),revision=e.status().revision;
  await assert.rejects(batch([edit('game',{gameSharpness:2}),edit('movie',{color:101})]),/range/);
  assert.equal(writes(),count,'All values validate before the first durable commit');
  assert.equal(e.status().revision,revision);
  assert.equal(f.values.game.gameSharpness,0,'An invalid later edit cannot partially apply an earlier one');
  await assert.rejects(batch([edit('game',{gameSharpness:2}),edit('game',{gameSharpness:3})]),/Duplicate/);
  await assert.rejects(batch([edit('movie',{backlight:5},'dark')],{preferences:{movie_dark:8}}),/Conflicting/);
  await assert.rejects(batch([],{preferences:JSON.parse('{"__proto__":{}}')}),/Unexpected/);
  await assert.rejects(batch([],{preferences:[]}),/Invalid/);
  await assert.rejects(batch([null]),/Invalid/);
  await assert.rejects(batch([edit('game',{gameSharpness:2})],{revision:0}),/refresh/);
  assert.equal(writes(),count);
  await batch([edit('game',{gameSharpness:2}),edit('movie',{color:51}),edit('movie',{color:52},'bright')]);await e.idle();
  assert.equal(writes(),count+1,'A broad edit persists the standards document once');
  assert.equal(e.status().revision,revision+1);
  assert.equal(f.values.game.gameSharpness,2);
  assert.equal(f.values.movie.color,51,'Inactive bright-room variant cannot alter dark-room viewing');
  assert.deepEqual(f.inspections.slice(-2),['game','movie'],'Multiple variants reuse one native inspection per bank');
  count=writes();revision=e.status().revision;
  await batch([edit('game',{gameSharpness:'2'})]);await e.idle();
  assert.equal(writes(),count,'Semantically identical standards cause no flash write or revision');
  assert.equal(e.status().revision,revision);
  await batch([],{preferences:{movie_dark:8}});await e.idle();
  assert.equal(writes(),count+1);
  assert.equal(f.values.movie.backlight,8);assert.equal(f.values.movie2.backlight,8,'Shared preferences reach all matching native banks');
  f.observe(e,'movie','realCinema','off');f.observe(e,'movie','color',57);
  await e.command(selection('restore',{movie:['realCinema']}));await e.idle();
  assert.equal(f.values.movie.realCinema,'on');assert.equal(f.values.movie.color,57);
  assert.equal(e.snapshot().overrides.movie.color,57,'Restoring Motion preserves unrelated Picture adjustments in the same bank');
  f.observe(e,'movie','realCinema','off');
  await e.command(selection('save',{movie:['realCinema']},{movie:{realCinema:'off'}}));await e.idle();
  assert.equal(e.snapshot().document.banks[1].settings.realCinema,'off');
  assert.equal(e.snapshot().overrides.movie.color,57,'Keeping Motion preserves unselected temporary adjustments');
  await assert.rejects(e.command(selection('save',{movie:['color']},{movie:{color:56}})),/changed/);
  await assert.rejects(e.command({...selection('restore',{movie:['color']}),room:'bright'}),/Room changed/);
  await assert.rejects(e.command(selection('restore',{movie:[]})),/explicit/);
  await assert.rejects(e.command(selection('restore',{movie:['color','color']})),/explicit/);
  f.observe(e,'movie','backlight',10);f.observe(e,'movie2','backlight',11);
  await assert.rejects(e.command(selection('save',{movie:['backlight'],movie2:['backlight']},{movie:{backlight:10},movie2:{backlight:11}})),/Conflicting/);
  f.observe(e,'movie2','backlight',8);
  await e.command(selection('save',{movie:['backlight']},{movie:{backlight:10}}));await e.idle();
  assert.equal(e.snapshot().preferences.movie_dark,10);assert.equal(f.values.movie2.backlight,10,'Keeping shared brightness updates other unmodified banks');
  assert.equal(f.values.movie.color,57);
  count=writes();
  f.inspectHook(()=>{e.setPower('off');e.setPower('on');});
  await assert.rejects(batch([edit('game',{gameSharpness:3})]),/session/);await e.idle();f.inspectHook(null);
  assert.equal(writes(),count,'A power-session change aborts the entire uncommitted batch');
  f.hook(async command=>{if(command.action==='apply')throw new Error('TV write failed');});
  await batch([edit('game',{gameSharpness:3}),edit('movie',{color:53})]);await e.idle();
  assert.equal(writes(),count+1);
  assert.equal(e.snapshot().document.banks[0].settings.gameSharpness,3);
  assert.equal(e.status().pending_restore,true,'A native failure retains the committed standards and durable retry intent');
  f.hook(null);await e.command({action:'reconcile'});
  assert.equal(f.values.game.gameSharpness,3);assert.equal(f.values.movie.color,53);assert.equal(e.status().pending_restore,false);
  e.stop();
};
