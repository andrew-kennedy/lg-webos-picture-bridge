'use strict';
const assert=require('node:assert/strict');
const view=require('../app/profile-view');
const fixture=require('./fixtures/profile-formats.cjs');
module.exports=()=>{
  const state=structuredClone(fixture),before=JSON.stringify(state),all=view.records(state);
  const cells=(scope,category='picture',split=['format'])=>view.scopeRows(all,scope,category,split);
  assert.equal(all.length,state.document.banks.reduce((n,b)=>n+Object.keys(b.settings).length,0));
  assert.equal(new Set(all.map(r=>r.id)).size,all.length);
  const categorized=Object.keys(view.categories).flatMap(c=>cells({},c,[]).flatMap(r=>r.cells.flatMap(c=>c.records.map(r=>r.id))));
  assert.deepEqual(categorized.sort(),all.map(r=>r.id).sort(),'Every native value appears once in its semantic category');
  const color=cells({port:['hdmi1'],format:['sdr']}).find(r=>r.key==='color').cells[0];
  assert.deepEqual(color.records.map(r=>[r.bank.id,r.key]),[['pc_sdr','color'],['pc_sdr_game','gameColorDepth'],['pc_sdrALLM_game','gameColorDepth']]);
  const real=cells({format:['sdr']},'motion').find(r=>r.key==='realCinema').cells[0];
  assert.deepEqual([...new Set(real.records.map(r=>r.value))],['off','on'],'Mixed gaming/movie motion values remain intact');
  assert.equal(cells({format:['sdr'],family:['movie']},'motion').find(r=>r.key==='realCinema').cells[0].records.length,1);
  assert.equal(cells({port:['hdmi1'],format:['sdr'],allm:['off']}).find(r=>r.key==='color').cells[0].records.length,2);
  assert.equal(cells({port:['hdmi1'],format:['sdr'],allm:['on']}).find(r=>r.key==='color').cells[0].records.length,2);
  const brightness=cells({port:['hdmi1'],format:['sdr']}).find(r=>r.key==='backlight').cells.find(c=>c.brightnessRole==='game_sdr');
  assert.equal(brightness.records.length,3,'A narrowed port filter still previews the full shared preference');
  assert.equal(brightness.label,'All SDR game profiles');
  const brightnessRows=cells({}).filter(r=>r.key==='backlight');
  assert.equal(brightnessRows.length,1,'All formats share one visible OLED brightness heading');
  assert.deepEqual(brightnessRows[0].cells.map(c=>c.label),['All SDR game profiles','SDR movie profiles','HDR','Dolby Vision']);
  assert(brightnessRows[0].cells.filter(c=>!c.brightnessRole).every(c=>c.records.every(r=>!r.locked&&!r.preference)),'HDR and DV remain ordinary editable per-profile standards');
  const combinedBrightness=cells({},'picture',[]).find(r=>r.key==='backlight').cells;
  assert.deepEqual(combinedBrightness.map(c=>c.label),['All SDR game profiles','SDR movie profiles','HDR / Dolby Vision']);
  assert.equal(combinedBrightness[2].records.length,6,'Collapsing formats keeps HDR/DV separate from shared SDR preferences');
  const ports=cells({},'port',['format']).find(r=>r.key==='enableQFT');
  assert.equal(ports.cells.length,1,'Connection options do not invent format-specific native values');
  assert.equal(ports.cells[0].records.length,3);
  assert.deepEqual(ports.cells[0].records.find(r=>r.port==='hdmi3').devices,['switch','apple','shield']);
  const movies=cells({family:['movie']},'selection');
  assert.equal(movies[0].cells.flatMap(c=>c.records).length,3,'Preset family scopes include only the matching mappings');
  assert(cells({},'selection').flatMap(r=>r.cells.flatMap(c=>c.records)).some(r=>r.bank.id==='switch_dv_unused_mapping'),'Dormant mappings remain accessible');
  const live={};color.records.forEach(({bank,key})=>{live[bank.id]={controls:{[key]:{component:'number',min:0,max:100,step:1}}};});
  live.pc_sdr_game.controls.gameColorDepth.min=10;live.pc_sdrALLM_game.controls.gameColorDepth.max=80;
  assert.deepEqual(view.combinedControl(color,live),{component:'number',min:10,max:80,step:1},'Grouped sliders use the intersection of native ranges');
  delete live.pc_sdr_game;assert.equal(view.combinedControl(color,live),null,'Every native target must have metadata before writing');
  const dv=cells({format:['dolbyHdr']}).find(r=>r.key==='color').cells[0];
  assert.equal(dv.records.length,2,'Both actual DV presets remain independently editable');
  assert.equal(cells({format:['dolbyHdr'],preset:['dolbyHdrCinemaBright']}).find(r=>r.key==='color').cells[0].records.length,1);
  const dark=view.records(state,'dark'),bright=view.records(state,'bright');
  assert.equal(dark.find(r=>r.id==='movie_filmMaker:backlight').preference,'movie_dark');
  assert.equal(bright.find(r=>r.id==='movie_filmMaker:backlight').preference,'movie_bright');
  assert(all.find(r=>r.id==='movie_filmMaker:backlight').locked);
  assert.equal(JSON.stringify(state),before,'Browsing and grouping never mutate standards');
  assert(view.same('50',50));assert(!view.same(50,55));
};
