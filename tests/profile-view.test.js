'use strict';
const assert=require('node:assert/strict');
const view=require('../app/profile-view');
const fixture=require('./fixtures/profile-formats.cjs');
module.exports=()=>{
  const state=JSON.parse(JSON.stringify(fixture)),before=JSON.stringify(state);
  const formats=(device,variant='standard')=>view.groups(state,variant,'profiles').filter(g=>g.devices.includes(device));
  for(const device of ['pc','ps5','switch'])assert.deepEqual(formats(device).map(g=>g.name),['SDR','HDR']);
  for(const device of ['apple','shield'])assert.deepEqual(formats(device).map(g=>g.name),['SDR','HDR','Dolby Vision']);
  const pc=formats('pc')[0],sections=view.rows(pc),color=sections.flatMap(s=>s.rows).find(r=>r.key==='color');
  assert.equal(color.bindings.length,3,'One color control covers picture, normal Game Optimizer and ALLM');
  assert.deepEqual(color.bindings.map(r=>[r.bank.id,r.key]),[['pc_sdr','color'],['pc_sdr_game','gameColorDepth'],['pc_sdrALLM_game','gameColorDepth']]);
  assert.deepEqual(sections.map(s=>s.name),['Picture','Game Optimizer','Motion']);
  assert.equal(sections.find(s=>s.name==='Game Optimizer').rows.length,1,'Only distinct game controls remain');
  assert(pc.scopeBanks.some(b=>b.id==='pc_sdrALLM_mapping'),'Restore also restores preset selection');
  assert(!pc.scopeBanks.some(b=>b.id==='pc_port'||b.id.startsWith('pc_hdr')),'SDR actions cannot touch HDMI options or HDR');
  const switchHdr=formats('switch')[1];
  assert(!switchHdr.banks.some(b=>b.devices.includes('apple')),'Shared HDMI does not mix gaming and movie owners');
  const dark=formats('apple','dark')[2],bright=formats('apple','bright')[2];
  assert(dark.banks.some(b=>b.id==='movie_dolbyHdrCinema'));
  assert(!dark.banks.some(b=>b.id==='movie_dolbyHdrCinemaBright'));
  assert(bright.banks.some(b=>b.id==='movie_dolbyHdrCinemaBright'));
  assert(!bright.banks.some(b=>b.id==='movie_dolbyHdrCinema'));
  const inputs=view.groups(state,'standard','input');
  assert.equal(inputs.length,3);
  assert.deepEqual(inputs.find(g=>g.id==='switch_port').devices,['switch','apple','shield'],'Physical HDMI options are shared by downstream devices');
  assert.equal(view.groups(state,'standard','advanced').length,state.document.banks.length,'Every native bank stays accessible');
  assert.equal(JSON.stringify(state),before,'Presentation must never modify stored standards');
  const live={};
  color.bindings.forEach(({bank,key})=>{live[bank.id]={controls:{[key]:{component:'number',min:0,max:100,step:1}}};});
  live.pc_sdr_game.controls.gameColorDepth.min=10;
  live.pc_sdrALLM_game.controls.gameColorDepth.max=80;
  assert.deepEqual(view.control(color,live),{component:'number',min:10,max:80,step:1},'Merged controls use the intersection of native limits');
  delete live.pc_sdr_game;
  assert.equal(view.control(color,live),null,'Wait for every target description before allowing a merged write');
  assert(view.same('50',50));assert(!view.same(50,55));
  const mapping=state.document.banks.find(b=>b.id==='pc_sdr_mapping');mapping.settings.pictureMode='filmMaker';
  assert(formats('pc')[0].missingPreset,'Do not pretend an unconfigured preset has saved picture values');
  assert(!formats('pc')[0].banks.some(b=>b.id==='pc_sdr_game'),'Movie routing excludes that signal’s Game Optimizer controls');
};
