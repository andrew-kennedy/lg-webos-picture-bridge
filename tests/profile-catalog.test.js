'use strict';
const assert=require('node:assert/strict');
const {fixture,doc}=require('./profile-engine.test');
const model=require('../app/bridge/lib/profile-model');
const catalog=require('../app/bridge/lib/profile-catalog');
const view=require('../app/profile-view');
module.exports=async function() {
  const original=model.clone(doc);
  original.banks[1].variants={bright:{color:51},dark:{color:50}};
  const f=fixture(original);let e=f.create();e.setPower('on');await e.idle();
  await e.command({action:'initialize',document:original,enabled:true,migration_id:'old-ha',room:'dark'});
  f.observe(e,'game','gameSharpness',8);
  const beforeNative=f.operations.length;
  await e.command({action:'upgrade_profiles',revision:e.status().revision});
  assert.equal(e.snapshot().document.schema,2);
  assert.equal(e.snapshot().overrides.game.gameSharpness,8,'Upgrade preserves temporary edits');
  assert.equal(f.operations.length,beforeNative,'Schema migration never touches native settings');
  assert.equal(f.files.profiles.preferences,undefined,'Shared brightness has one persistent owner');
  for(const bank of original.banks)for(const room of ['bright','dark'])assert.deepEqual(
    view.values(e.snapshot().document.banks.find(b=>b.id===bank.id),e.snapshot(),room),
    model.desired(bank,room,{game_sdr:80,movie_dark:3,movie_bright:100}),'Lossless legacy migration');
  const revision=e.status().revision,writes=f.writes.length;
  await e.command({action:'upgrade_profiles',revision:0});
  assert.equal(e.status().revision,revision);assert.equal(f.writes.length,writes,'Migration is idempotent');
  const run=async fields=>{const result=await e.command({revision:e.status().revision,...fields});await e.idle();return result;};
  const id=(await run({action:'create_profile',name:'Evening'})).profile_id;
  assert.match(id,/^p_/);assert.equal(e.status().selection,'automatic');
  await run({action:'edit_many',edits:[{bank_id:'movie',variant:id,settings:{backlight:17,color:49}}]});
  assert.equal(f.values.movie.backlight,3,'Editing inactive named profile does not change viewing');
  assert.equal(view.values(e.snapshot().document.banks[1],e.snapshot(),id).color,49);
  const revBeforeSelect=e.status().revision;
  await run({action:'apply_profile',profile_id:id});
  assert.equal(e.status().revision,revBeforeSelect,'Selections do not create standard revisions/backup history');
  assert.equal(f.values.movie.backlight,17);assert.equal(f.values.movie.color,49);
  assert.equal(f.values.game.gameSharpness,0,'Explicit application clears temporary adjustments');
  await run({action:'set_environment',room:'bright'});
  assert.equal(f.values.movie.backlight,17,'Sunset/sunrise cannot override a manual selection');
  e.stop();e=f.create();e.setPower('on');await e.idle();
  assert.equal(e.status().active_profile,id,'Manual profile survives a process restart');
  assert.equal(e.status().room,'bright','Ambient context survives a manual-profile restart');
  f.observe(e,'movie','color',48);
  e.setPower('off');await e.idle();e.setPower('on');await e.idle();
  assert.equal(f.values.movie.color,49,'Power cycles restore the selected named standard');
  await run({action:'rename_profile',profile_id:id,name:'Late evening'});
  assert.equal(e.status().active_profile,id,'Rename does not change automation identity');
  const copy=(await run({action:'create_profile',name:'Cinema evening',copy_from:id})).profile_id;
  await run({action:'edit',bank_id:'game',variant:'standard',settings:{gameColorDepth:52}});
  assert.equal(view.values(e.snapshot().document.banks[0],e.snapshot(),copy).gameColorDepth,52,'Copies inherit later base changes');
  await run({action:'set_brightness_links',links:[{bank_id:'movie',linked:false}]});
  assert.equal(view.values(e.snapshot().document.banks[1],e.snapshot(),copy).backlight,17,'Unlink preserves every named value');
  await run({action:'edit',bank_id:'movie',variant:copy,settings:{backlight:22}});
  assert.equal(view.values(e.snapshot().document.banks[1],e.snapshot(),id).backlight,17);
  await run({action:'set_brightness_links',links:[{bank_id:'movie',linked:true}]});
  assert.equal(view.values(e.snapshot().document.banks[1],e.snapshot(),copy).backlight,17,'Relinking uses selected profile shared brightness');
  await run({action:'set_automatic',profiles:{bright:copy,dark:'dark'}});
  await run({action:'apply_profile',profile_id:'automatic'});
  assert.equal(e.status().active_profile,copy);
  f.observe(e,'movie','backlight',30);
  await run({action:'set_environment',room:'dark'});
  assert.equal(f.values.movie.backlight,30,'Automatic transitions preserve temporary edits');
  await run({action:'save',scope:'movie'});
  assert.equal(e.snapshot().document.profiles.find(p=>p.id==='dark').brightness.movie_sdr,30);
  assert.equal(e.snapshot().document.brightness.movie_sdr,3,'Keep adjustments saves the active profile, not base');
  await assert.rejects(run({action:'delete_profile',profile_id:copy}),/bindings/);
  await assert.rejects(run({action:'create_profile',name:'late EVENING'}),/unique/);
  await assert.rejects(run({action:'apply_profile',profile_id:'__proto__'}),/Unknown/);
  await assert.rejects(run({action:'edit',bank_id:'movie',variant:id,settings:{backlight:101}}),/range/);
  await assert.rejects(run({action:'edit_many',preferences:{movie_dark:9},edits:[{bank_id:'movie',variant:'dark',settings:{backlight:10}}]}),/Conflicting/);
  await assert.rejects(run({action:'restore',selection:{movie:['color']},room:'dark',profile_id:id}),/changed/);
  const backup=await e.command({action:'backup'});
  assert.deepEqual(model.decodeBackup(backup).document,e.snapshot().document);
  await run({action:'apply_profile',profile_id:id});
  await run({action:'reset_profile',profile_id:id});
  assert.equal(f.values.movie.color,50);assert.equal(f.values.movie.backlight,3);
  await run({action:'delete_profile',profile_id:id});
  assert.equal(e.status().selection,'automatic');assert.equal(e.status().active_profile,'dark');
  assert.equal(f.values.movie.backlight,30,'Deleting selected profile applies the automatic fallback');
  e.setPower('off');await e.idle();
  await run({action:'apply_profile',profile_id:copy});
  assert.equal(e.status().pending_restore,true);
  e.setPower('on');await e.idle();assert.equal(f.values.movie.backlight,17,'Offline selection applies on power-on');
  const data=model.clone(e.snapshot().document);data.profiles[0].id='constructor';
  assert.throws(()=>model.validate(data),/unique/);
  assert.throws(()=>catalog.validate({...e.snapshot().document,automatic:{bright:'missing',dark:'dark'}}),/automatic/);
  e.stop();
};
